-- Plotwise: CRM + Deal Finder + Property Management
-- Target: MySQL 8 (Aiven). `npm run migrate` applies this file; or run it in DBeaver (Alt+X).

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ---------------------------------------------------------------
-- SHARED CORE
-- ---------------------------------------------------------------
CREATE TABLE users (
  id            BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(190) NOT NULL UNIQUE,
  phone         VARCHAR(30),
  password_hash VARCHAR(255) NOT NULL,
  role          ENUM('admin','agent','landlord','tenant','buyer') NOT NULL DEFAULT 'buyer',
  telegram_chat_id VARCHAR(60),
  is_active     TINYINT(1) NOT NULL DEFAULT 1,
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_users_role (role)
) ENGINE=InnoDB;

CREATE TABLE properties (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  owner_id        BIGINT UNSIGNED NULL,               -- landlord / seller
  agent_id        BIGINT UNSIGNED NULL,
  title           VARCHAR(190) NOT NULL,
  description     TEXT,
  ai_description  TEXT,                               -- generated by automation
  social_posts    JSON NULL,                          -- generated by automation
  listing_type    ENUM('sale','rent') NOT NULL,
  status          ENUM('draft','active','under_offer','sold','rented','managed','archived') NOT NULL DEFAULT 'draft',
  property_type   ENUM('house','apartment','plot','commercial') NOT NULL DEFAULT 'house',
  price           DECIMAL(14,2) NOT NULL,             -- sale price or monthly rent
  currency        CHAR(3) NOT NULL DEFAULT 'PKR',
  bedrooms        TINYINT UNSIGNED,
  bathrooms       TINYINT UNSIGNED,
  area_sqft       INT UNSIGNED,
  address         VARCHAR(255),
  city            VARCHAR(80),
  lat             DECIMAL(9,6),
  lng             DECIMAL(9,6),
  source          ENUM('manual','import','deal_finder') NOT NULL DEFAULT 'manual',
  market_listing_id BIGINT UNSIGNED NULL,             -- set when promoted from Deal Finder
  created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (agent_id) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_prop_search (status, listing_type, city, price),
  INDEX idx_prop_geo (lat, lng)
) ENGINE=InnoDB;

CREATE TABLE property_images (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  property_id BIGINT UNSIGNED NOT NULL,
  url         VARCHAR(500) NOT NULL,
  sort_order  SMALLINT NOT NULL DEFAULT 0,
  is_cover    TINYINT(1) NOT NULL DEFAULT 0,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------
-- MODULE 1: SALES CRM (leads, viewings, messages)
-- ---------------------------------------------------------------
CREATE TABLE leads (
  id                BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  property_id       BIGINT UNSIGNED NULL,
  assigned_agent_id BIGINT UNSIGNED NULL,
  user_id           BIGINT UNSIGNED NULL,             -- linked account once they register
  name              VARCHAR(120) NOT NULL,
  email             VARCHAR(190),
  phone             VARCHAR(30),
  message           TEXT,
  budget            DECIMAL(14,2),
  source            ENUM('website','whatsapp','referral','social','portal','demo') NOT NULL DEFAULT 'website',
  status            ENUM('new','contacted','viewing_booked','negotiation','won','lost') NOT NULL DEFAULT 'new',
  score             TINYINT UNSIGNED,                 -- 0-100, set by AI
  score_label       ENUM('hot','warm','cold'),
  score_reason      VARCHAR(500),
  last_contacted_at DATETIME,
  next_followup_at  DATETIME,
  followup_step     TINYINT UNSIGNED NOT NULL DEFAULT 0,  -- 0 none, 1=day3, 2=day7, 3=day14
  created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE SET NULL,
  FOREIGN KEY (assigned_agent_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_leads_status (status, score_label),
  INDEX idx_leads_followup (next_followup_at)
) ENGINE=InnoDB;

CREATE TABLE lead_activities (
  id         BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lead_id    BIGINT UNSIGNED NOT NULL,
  type       ENUM('created','ai_reply_sent','scored','assigned','viewing_booked','followup_sent','note','status_change','lease_created') NOT NULL,
  details    JSON,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (lead_id) REFERENCES leads(id) ON DELETE CASCADE,
  INDEX idx_activity_lead (lead_id, created_at)
) ENGINE=InnoDB;

CREATE TABLE messages (                               -- every outbound/inbound message, AI or human
  id         BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lead_id    BIGINT UNSIGNED NULL,
  user_id    BIGINT UNSIGNED NULL,
  channel    ENUM('email','whatsapp','telegram','slack','sms') NOT NULL,
  direction  ENUM('outbound','inbound') NOT NULL DEFAULT 'outbound',
  subject    VARCHAR(190),
  body       TEXT NOT NULL,
  generated_by ENUM('ai','human','template') NOT NULL DEFAULT 'ai',
  status     ENUM('queued','sent','failed') NOT NULL DEFAULT 'queued',
  sent_at    DATETIME,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (lead_id) REFERENCES leads(id) ON DELETE SET NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE viewings (
  id                BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lead_id           BIGINT UNSIGNED NOT NULL,
  property_id       BIGINT UNSIGNED NOT NULL,
  agent_id          BIGINT UNSIGNED NULL,
  scheduled_at      DATETIME NOT NULL,
  status            ENUM('scheduled','completed','cancelled','no_show') NOT NULL DEFAULT 'scheduled',
  calendar_event_id VARCHAR(190),
  reminder_sent     TINYINT(1) NOT NULL DEFAULT 0,
  feedback          TEXT,
  created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (lead_id) REFERENCES leads(id) ON DELETE CASCADE,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE,
  FOREIGN KEY (agent_id) REFERENCES users(id) ON DELETE SET NULL,
  INDEX idx_viewings_time (scheduled_at, status)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------
-- MODULE 2: DEAL FINDER
-- ---------------------------------------------------------------
CREATE TABLE market_listings (
  id                   BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  source               VARCHAR(60) NOT NULL,           -- 'csv_import', 'api:xyz', 'seed'
  external_id          VARCHAR(120) NOT NULL,
  title                VARCHAR(190),
  listing_type         ENUM('sale','rent') NOT NULL DEFAULT 'sale',
  property_type        ENUM('house','apartment','plot','commercial') NOT NULL DEFAULT 'house',
  price                DECIMAL(14,2) NOT NULL,
  bedrooms             TINYINT UNSIGNED,
  area_sqft            INT UNSIGNED,
  city                 VARCHAR(80),
  area_name            VARCHAR(120),
  lat                  DECIMAL(9,6),
  lng                  DECIMAL(9,6),
  url                  VARCHAR(500),
  estimated_price      DECIMAL(14,2),                  -- model / comps estimate
  price_gap_pct        DECIMAL(6,2),                   -- (estimated - price) / estimated * 100
  is_undervalued       TINYINT(1) NOT NULL DEFAULT 0,
  raw                  JSON,
  promoted_property_id BIGINT UNSIGNED NULL,
  imported_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_market (source, external_id),
  INDEX idx_market_deal (is_undervalued, price_gap_pct),
  FOREIGN KEY (promoted_property_id) REFERENCES properties(id) ON DELETE SET NULL
) ENGINE=InnoDB;

ALTER TABLE properties
  ADD CONSTRAINT fk_prop_market FOREIGN KEY (market_listing_id) REFERENCES market_listings(id) ON DELETE SET NULL;

CREATE TABLE saved_searches (
  id         BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id    BIGINT UNSIGNED NOT NULL,
  name       VARCHAR(120) NOT NULL,
  filters    JSON NOT NULL,                            -- {city, min_price, max_price, beds, type, min_gap_pct}
  frequency  ENUM('instant','daily','weekly') NOT NULL DEFAULT 'instant',
  channel    ENUM('email','telegram','whatsapp') NOT NULL DEFAULT 'email',
  is_active  TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE alerts (
  id                BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  saved_search_id   BIGINT UNSIGNED NOT NULL,
  market_listing_id BIGINT UNSIGNED NULL,
  property_id       BIGINT UNSIGNED NULL,
  sent_at           DATETIME,
  created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (saved_search_id) REFERENCES saved_searches(id) ON DELETE CASCADE,
  FOREIGN KEY (market_listing_id) REFERENCES market_listings(id) ON DELETE CASCADE,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE,
  UNIQUE KEY uq_alert (saved_search_id, market_listing_id)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------
-- MODULE 3: PROPERTY MANAGEMENT
-- ---------------------------------------------------------------
CREATE TABLE leases (
  id           BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  property_id  BIGINT UNSIGNED NOT NULL,
  tenant_id    BIGINT UNSIGNED NOT NULL,
  landlord_id  BIGINT UNSIGNED NOT NULL,
  lead_id      BIGINT UNSIGNED NULL,                   -- CRM lead that became this tenant
  start_date   DATE NOT NULL,
  end_date     DATE NOT NULL,
  monthly_rent DECIMAL(12,2) NOT NULL,
  deposit      DECIMAL(12,2) NOT NULL DEFAULT 0,
  rent_due_day TINYINT UNSIGNED NOT NULL DEFAULT 1,
  status       ENUM('active','expiring','ended','terminated') NOT NULL DEFAULT 'active',
  created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE,
  FOREIGN KEY (tenant_id) REFERENCES users(id),
  FOREIGN KEY (landlord_id) REFERENCES users(id),
  FOREIGN KEY (lead_id) REFERENCES leads(id) ON DELETE SET NULL,
  INDEX idx_leases_end (status, end_date)
) ENGINE=InnoDB;

CREATE TABLE rent_payments (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  lease_id    BIGINT UNSIGNED NOT NULL,
  due_date    DATE NOT NULL,
  amount      DECIMAL(12,2) NOT NULL,
  paid_at     DATETIME,
  method      ENUM('bank','cash','card','online'),
  status      ENUM('pending','paid','overdue') NOT NULL DEFAULT 'pending',
  reminders_sent TINYINT UNSIGNED NOT NULL DEFAULT 0,
  FOREIGN KEY (lease_id) REFERENCES leases(id) ON DELETE CASCADE,
  UNIQUE KEY uq_rent (lease_id, due_date),
  INDEX idx_rent_status (status, due_date)
) ENGINE=InnoDB;

CREATE TABLE vendors (
  id        BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name      VARCHAR(120) NOT NULL,
  trade     ENUM('plumbing','electrical','hvac','carpentry','cleaning','general') NOT NULL,
  phone     VARCHAR(30),
  email     VARCHAR(190),
  is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;

CREATE TABLE maintenance_tickets (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  property_id BIGINT UNSIGNED NOT NULL,
  lease_id    BIGINT UNSIGNED NULL,
  reported_by BIGINT UNSIGNED NOT NULL,
  vendor_id   BIGINT UNSIGNED NULL,
  title       VARCHAR(190) NOT NULL,
  description TEXT,
  category    ENUM('plumbing','electrical','hvac','carpentry','cleaning','general'),  -- AI-assigned
  urgency     ENUM('low','medium','high','emergency'),                                -- AI-assigned
  ai_summary  VARCHAR(500),
  status      ENUM('open','assigned','in_progress','resolved','closed') NOT NULL DEFAULT 'open',
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at DATETIME,
  FOREIGN KEY (property_id) REFERENCES properties(id) ON DELETE CASCADE,
  FOREIGN KEY (lease_id) REFERENCES leases(id) ON DELETE SET NULL,
  FOREIGN KEY (reported_by) REFERENCES users(id),
  FOREIGN KEY (vendor_id) REFERENCES vendors(id) ON DELETE SET NULL,
  INDEX idx_tickets_status (status, urgency)
) ENGINE=InnoDB;

CREATE TABLE owner_statements (
  id           BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  landlord_id  BIGINT UNSIGNED NOT NULL,
  period       CHAR(7) NOT NULL,                       -- 'YYYY-MM'
  rent_collected DECIMAL(14,2) NOT NULL DEFAULT 0,
  expenses     DECIMAL(14,2) NOT NULL DEFAULT 0,
  pdf_url      VARCHAR(500),
  sent_at      DATETIME,
  FOREIGN KEY (landlord_id) REFERENCES users(id),
  UNIQUE KEY uq_statement (landlord_id, period)
) ENGINE=InnoDB;

-- ---------------------------------------------------------------
-- AUTOMATION LOG (powers the "automation runs" page and demo)
-- ---------------------------------------------------------------
CREATE TABLE automation_runs (
  id          BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  workflow    VARCHAR(80) NOT NULL,                    -- 'instant_reply', 'lead_scoring', 'rent_reminder', ...
  trigger_type ENUM('webhook','schedule','manual') NOT NULL DEFAULT 'webhook',
  entity_type VARCHAR(40),
  entity_id   BIGINT UNSIGNED,
  status      ENUM('running','success','failed','skipped') NOT NULL DEFAULT 'running',
  duration_ms INT UNSIGNED,
  error       TEXT,
  payload     JSON,
  started_at  TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  finished_at DATETIME(3),
  INDEX idx_runs_workflow (workflow, started_at)
) ENGINE=InnoDB;

SET FOREIGN_KEY_CHECKS = 1;
